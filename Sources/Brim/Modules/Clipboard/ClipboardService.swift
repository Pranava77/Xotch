import AppKit
import SwiftUI
import Observation

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case text, link, files, image
    }

    var id = UUID()
    var kind: Kind
    var text: String?
    var paths: [String]?
    /// PNG file name in the ClipImages folder.
    var imageFile: String?
    var sourceApp: String?
    var date: Date
    var pinned = false

    var preview: String {
        switch kind {
        case .text, .link:
            return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .files:
            let names = (paths ?? []).map { ($0 as NSString).lastPathComponent }
            return names.count > 1 ? "\(names[0]) and \(names.count - 1) more" : (names.first ?? "Files")
        case .image:
            return "Image"
        }
    }
}

/// Keeps a local history of what you copy. Watches the pasteboard's change
/// counter (cheap) and only reads contents when it changes. Skips anything a
/// password manager marks as concealed.
@MainActor
@Observable
final class ClipboardService {
    static let shared = ClipboardService()
    static let limit = 200

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]
    private static let ignoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
    ]

    private(set) var items: [ClipItem]
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private lazy var saver = SaveScheduler { [weak self] in
        guard let self else { return }
        Storage.save(self.items, to: "clipboard.json")
    }
    @ObservationIgnored private let imageFolder = Storage.folder("ClipImages")

    init() {
        items = Storage.load([ClipItem].self, from: "clipboard.json") ?? []
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.6, repeats: true) { @Sendable [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard AppSettings.clipboardHistory else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Self.ignoredApps.contains(source) { return }

        let now = Date()
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            insert(ClipItem(kind: .files, paths: urls.map(\.path), sourceApp: source, date: now))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(where: \.isWhitespace)
                && (URL(string: trimmed)?.scheme.map { ["http", "https"].contains($0) } ?? false)
            insert(ClipItem(kind: isLink ? .link : .text, text: String(string.prefix(20_000)), sourceApp: source, date: now))
        } else if let image = NSImage(pasteboard: pasteboard), let file = saveImage(image) {
            insert(ClipItem(kind: .image, imageFile: file, sourceApp: source, date: now))
        }
    }

    private func insert(_ item: ClipItem) {
        var item = item
        if let existing = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.paths == item.paths && item.kind != .image }) {
            item.pinned = items[existing].pinned
            item.id = items[existing].id
            items.remove(at: existing)
        }
        withAnimation(Motion.switchModule) {
            items.insert(item, at: 0)
            trim()
        }
        saver.schedule()
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            if unpinned <= Self.limit { return true }
            deleteImage(of: item)
            return false
        }
    }

    // MARK: - Actions

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            pasteboard.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        }
        lastChangeCount = pasteboard.changeCount
        var moved = item
        moved.date = Date()
        withAnimation(Motion.switchModule) {
            items.removeAll { $0.id == item.id }
            items.insert(moved, at: 0)
        }
        saver.schedule()
        Haptics.tick()
        ActivityCenter.shared.post(LiveActivity(moduleID: "clipboard", symbol: "doc.on.clipboard.fill",
                                                content: .text("Copied"), tint: Theme.accent,
                                                duration: .seconds(1.6)))
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        withAnimation(Motion.press) { items[index].pinned.toggle() }
        saver.schedule()
    }

    func delete(_ item: ClipItem) {
        deleteImage(of: item)
        withAnimation(Motion.switchModule) { items.removeAll { $0.id == item.id } }
        saver.schedule()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteImage)
        withAnimation(Motion.switchModule) { items.removeAll { !$0.pinned } }
        saver.schedule()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let file = item.imageFile else { return nil }
        return NSImage(contentsOf: imageFolder.appendingPathComponent(file))
    }

    // MARK: - Images

    private func saveImage(_ image: NSImage) -> String? {
        let maxSide: CGFloat = 1600
        let scale = min(1, maxSide / max(image.size.width, image.size.height, 1))
        let size = NSSize(width: image.size.width * scale, height: image.size.height * scale)
        guard size.width >= 1, size.height >= 1 else { return nil }
        let resized = NSImage(size: size, flipped: false) { rect in
            image.draw(in: rect)
            return true
        }
        guard let tiff = resized.tiffRepresentation,
              let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        do {
            try png.write(to: imageFolder.appendingPathComponent(name))
            return name
        } catch {
            return nil
        }
    }

    private func deleteImage(of item: ClipItem) {
        guard let file = item.imageFile else { return }
        try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent(file))
    }

    #if DEBUG
    func withSample(_ body: () -> Void) {
        let saved = items
        let now = Date()
        items = [
            ClipItem(kind: .link, text: "https://github.com/Pranava77/Brim", sourceApp: "com.apple.Safari", date: now.addingTimeInterval(-40)),
            ClipItem(kind: .text, text: "Ship the notch shell, then Now Playing and Calendar.", sourceApp: "com.apple.Notes", date: now.addingTimeInterval(-600), pinned: true),
            ClipItem(kind: .files, paths: ["/Users/you/Desktop/brim-hero.mov", "/Users/you/Desktop/icon.png"], sourceApp: "com.apple.finder", date: now.addingTimeInterval(-3600)),
            ClipItem(kind: .text, text: "swift build -c release", sourceApp: "com.apple.Terminal", date: now.addingTimeInterval(-7200)),
        ]
        body()
        items = saved
    }
    #endif
}
